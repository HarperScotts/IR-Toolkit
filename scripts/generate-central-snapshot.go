//go:build ignore

// Prints Central's defensive-copy methods. From the repository root:
// go run scripts/generate-central-snapshot.go
// Apply stdout to internal/store/central/snapshot_methods.go.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"strings"
)

func typeName(expression ast.Expr) string {
	switch value := expression.(type) {
	case *ast.Ident:
		if ast.IsExported(value.Name) {
			return "store." + value.Name
		}
		return value.Name
	case *ast.SelectorExpr:
		return typeName(value.X) + "." + value.Sel.Name
	case *ast.StarExpr:
		return "*" + typeName(value.X)
	case *ast.ArrayType:
		if value.Len != nil {
			panic("array lengths require generator support")
		}
		return "[]" + typeName(value.Elt)
	case *ast.MapType:
		return "map[" + typeName(value.Key) + "]" + typeName(value.Value)
	case *ast.IndexExpr:
		return typeName(value.X) + "[" + typeName(value.Index) + "]"
	default:
		panic(fmt.Sprintf("unsupported contract type %T", expression))
	}
}

func main() {
	file, err := parser.ParseFile(token.NewFileSet(), "internal/store/store.go", nil, 0)
	if err != nil {
		panic(err)
	}
	interfaces := map[string]*ast.InterfaceType{}
	for _, declaration := range file.Decls {
		general, ok := declaration.(*ast.GenDecl)
		if !ok {
			continue
		}
		for _, specification := range general.Specs {
			if named, ok := specification.(*ast.TypeSpec); ok {
				if contract, ok := named.Type.(*ast.InterfaceType); ok {
					interfaces[named.Name.Name] = contract
				}
			}
		}
	}
	var output bytes.Buffer
	fmt.Fprintln(&output, "// Code generated by scripts/generate-central-snapshot.go; DO NOT EDIT.")
	fmt.Fprintln(&output, "package central\nimport (\"ir-toolkit/internal/model\"; \"ir-toolkit/internal/store\")")
	var visit func(string)
	visit = func(name string) {
		for _, method := range interfaces[name].Methods.List {
			if len(method.Names) == 0 {
				visit(method.Type.(*ast.Ident).Name)
				continue
			}
			signature := method.Type.(*ast.FuncType)
			var parameters, arguments, results, variables, copies []string
			for index, parameter := range signature.Params.List {
				name := fmt.Sprintf("arg%d", index)
				parameters = append(parameters, name+" "+typeName(parameter.Type))
				arguments = append(arguments, "copySnapshotValue("+name+")")
			}
			for index, result := range signature.Results.List {
				name := fmt.Sprintf("result%d", index)
				kind := typeName(result.Type)
				results = append(results, kind)
				variables = append(variables, name)
				if kind == "error" {
					copies = append(copies, name)
				} else {
					copies = append(copies, "copySnapshotValue("+name+")")
				}
			}
			fmt.Fprintf(&output, "func (s *CaseStore) %s(%s) (%s) {\n%s := s.snapshot.%s(%s)\nreturn %s\n}\n",
				method.Names[0].Name, strings.Join(parameters, ", "), strings.Join(results, ", "),
				strings.Join(variables, ", "), method.Names[0].Name, strings.Join(arguments, ", "), strings.Join(copies, ", "))
		}
	}
	visit("CaseStore")
	formatted, err := format.Source(output.Bytes())
	if err != nil {
		panic(err)
	}
	if len(os.Args) == 3 && os.Args[1] == "-check" {
		existing, err := os.ReadFile(os.Args[2])
		if err != nil || !bytes.Equal(existing, formatted) {
			fmt.Fprintln(os.Stderr, "Central snapshot methods are out of date")
			os.Exit(1)
		}
		return
	}
	_, _ = os.Stdout.Write(formatted)
}
